const FALLBACK =
  'Я пока знаю ответы только про налоговые вычеты: лимиты, документы, сроки и за кого можно заявить. Попробуйте спросить, например: «Сколько можно вернуть?» или «Где взять справку?»'

export function findAnswer(question) {
  const q = question.toLowerCase().replace(/ё/g, 'е')
  let best = null
  let bestScore = 0
  for (const item of ANSWERS) {
    const score = item.keys.reduce((s, k) => (q.includes(k.replace(/ё/g, 'е')) ? s + 1 : s), 0)
    if (score > bestScore) {
      best = item
      bestScore = score
    }
  }
  return best ? best.text : FALLBACK
}
